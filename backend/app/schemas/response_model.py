from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class SourceDocument(BaseModel):
    """
    RAG source document details.
    """
    document_name: str = Field(..., description="Source document name")
    document_type: str = Field(..., description="Protocol, SOP, Monitoring Report, etc.")
    page_number: Optional[int] = Field(default=None)
    chunk_id: Optional[str] = Field(default=None)
    relevance_score: Optional[float] = Field(default=None)


class AgentExecution(BaseModel):
    """
    Information about the agent that handled the request.
    """
    agent_name: str
    module: str
    execution_time: float
    status: str


class SQLExecution(BaseModel):
    """
    SQL Agent execution details.
    """
    executed: bool = False
    query: Optional[str] = None
    rows_returned: Optional[int] = None
    data: Optional[List[Dict[str, Any]]] = None


class RetrievalExecution(BaseModel):
    """
    RAG retrieval details.
    """
    executed: bool = False
    retrieved_chunks: int = 0
    top_k: int = 0
    sources: List[SourceDocument] = Field(default_factory=list)


class CTMSResponse(BaseModel):
    """
    Standard response model for Enterprise CTMS Copilot.
    """

    status: str = Field(
        default="success",
        description="success | failed"
    )

    message: str = Field(
        default="Request processed successfully."
    )

    answer: str = Field(
        ...,
        description="Final response generated by the LLM."
    )

    module: str = Field(
        ...,
        description="Trial Planning, Budget, Monitoring, Site Management, Recruitment"
    )

    agent: str = Field(
        ...,
        description="Agent that generated the response"
    )

    sql_execution: Optional[SQLExecution] = None

    rag_execution: Optional[RetrievalExecution] = None

    agent_execution: Optional[AgentExecution] = None

    recommendations: List[str] = Field(default_factory=list)

    follow_up_questions: List[str] = Field(default_factory=list)

    charts: List[Dict[str, Any]] = Field(default_factory=list)

    tables: List[Dict[str, Any]] = Field(default_factory=list)

    metadata: Dict[str, Any] = Field(default_factory=dict)

    timestamp: Optional[str] = None